/**
 * Regenerate the built-in list of common passwords from a local checkout of SecLists (MIT licence).
 *
 *   git clone --depth 1 https://github.com/danielmiessler/SecLists /tmp/seclists
 *   npm run reference:passwords -w server -- --dir /tmp/seclists
 *
 * Only entries a new password could still be are kept: 12 characters or more (shorter ones are refused for
 * their length) and at most 72 bytes. They are lower-cased, because the comparison ignores capitals.
 *
 * Two files are written with the same entries: the server's list, and a copy the web app loads to say so
 * while the password is still being typed. A server test fails if the two differ.
 * The output is sorted, so running it twice gives no diff.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { characterCount, COMMON_PASSWORDS_FILE, PASSWORD_MAX_BYTES, PASSWORD_MIN_CHARACTERS } from '@/services/passwordRules';

const SOURCE_FILE = 'Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt';
const CLIENT_FILE = fileURLToPath(new URL('../../client/src/lib/commonPasswords.ts', import.meta.url));

const dirFlag = process.argv.indexOf('--dir');
const dir = dirFlag > -1 ? process.argv[dirFlag + 1] : undefined;
if (!dir) {
  console.error('Use: npm run reference:passwords -w server -- --dir <SecLists checkout>');
  process.exit(1);
}
const source = join(dir, SOURCE_FILE);
if (!existsSync(source)) {
  console.error(`Not found: ${source}`);
  process.exit(1);
}

const entries = [
  ...new Set(
    readFileSync(source, 'utf8')
      .split(/\r?\n/)
      .filter((line) => characterCount(line) >= PASSWORD_MIN_CHARACTERS && Buffer.byteLength(line, 'utf8') <= PASSWORD_MAX_BYTES)
      .map((line) => line.toLowerCase()),
  ),
].sort();

if (entries.length < 500) {
  console.error(`Only ${entries.length} entries found, which is far fewer than expected. Nothing was written.`);
  process.exit(1);
}

mkdirSync(dirname(COMMON_PASSWORDS_FILE), { recursive: true });
writeFileSync(COMMON_PASSWORDS_FILE, `${entries.join('\n')}\n`);
writeFileSync(
  CLIENT_FILE,
  [
    '// Generated by server/scripts/import-common-passwords.ts from SecLists (MIT licence). Do not edit by hand.',
    '// Common passwords of 12 characters or more, in lower case, one per line. The server holds the same list.',
    `export const COMMON_PASSWORDS = ${JSON.stringify(entries.join('\n'))};`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${entries.length} common passwords to the server and the web app.`);
